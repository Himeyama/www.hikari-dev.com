// Exercise the real shell and VFS with an isolated browser storage implementation.
const {readFileSync} = require('node:fs');
const {join} = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const storage = new Map();
const window = {localStorage: {getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v)}, dispatchEvent() {}};
function load(file, dependencies) {
  const source = ts.transpileModule(readFileSync(join(__dirname, '..', file), 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText;
  const exports = {};
  vm.runInNewContext(source, {exports, require: name => {if (!(name in dependencies)) throw new Error(name); return dependencies[name];}, window, TextEncoder, TextDecoder, CustomEvent: class {}, console});
  return exports;
}
const apps = {MINI_APPS: [{id:'base64', href:'/base64'}, {id:'chat', href:'/chat'}], LAUNCHABLES: [{id:'base64'}, {id:'chat'}], getAppById: id => ['base64','chat'].includes(id) ? {id} : undefined};
const vfs = load('src/lib/desktop/vfs.ts', {'../../components/desktop/apps': apps, './blobStore': {deleteBlobs: async () => {}}});
const {PromptShell} = load('src/lib/desktop/promptShell.ts', {'./vfs': vfs, '../../components/desktop/apps': apps});
const messages = Object.fromEntries(['missing', 'directory', 'file', 'exists', 'arguments', 'syntax', 'unknown', 'unsupported', 'protected', 'empty'].map(k => [k, k]));
const launched = [];
const shell = new PromptShell(messages, 'help', id => launched.push(id));
const run = s => shell.run(s).output;
assert.equal(run('pwd'), '/home/user\n');
assert.equal(shell.prompt, '[user@hikari-browser: ~]$ ');
assert.equal(run('./base64; ./chat'), '');
assert.equal(launched.join(','), 'base64,chat');
assert.equal(shell.complete('./ba')[0], './base64');
assert.equal(run('echo -e "one\\ntwo\\tthree"'), 'one\ntwo\tthree\n');
assert.equal(run("echo -ne '\\x41\\0102'"), 'AB');
assert.equal(run("echo -E 'one\\ntwo'"), 'one\\ntwo\n');
assert.equal(run("echo -e 'stop\\cignored'"), 'stop');
assert.equal(run('mkdir -p work/deep; cd work/deep; pwd'), '/home/user/work/deep\n');
assert.equal(shell.prompt, '[user@hikari-browser: ~/work/deep]$ ');
assert.equal(run('echo "hello world" > hello.txt; cat hello.txt | tr a-z A-Z'), 'HELLO WORLD\n');
assert.equal(run('echo second >> hello.txt; cat < hello.txt | wc -l'), '2\n');
assert.equal(run('printf "c\\na\\na\\nb\\n" | sort | uniq -c'), '2 a\n1 b\n1 c\n');
assert.equal(run('cat hello.txt | grep -n hello'), '1:hello world\n');
assert.equal(run('cat hello.txt | head -n 1'), 'hello world\n');
assert.equal(run('cat hello.txt | tail -n 1'), 'second\n');
assert.equal(run('cat hello.txt | head --lines=1'), 'hello world\n');
assert.equal(run('cat hello.txt | tail -n1'), 'second\n');
assert.equal(run('cat hello.txt | head -c5'), 'hello');
assert.equal(run('echo 日本語 | wc -m'), '4\n');
assert.equal(run('echo 日本語 | wc --bytes'), '10\n');
assert.equal(run("printf 'a.b\\naxb\\n' | grep -F a.b"), 'a.b\n');
assert.equal(run("echo 'abc 123' | grep -o '[0-9]+'"), '123\n');
assert.equal(run("printf 'two\\n\\n\\nthree\\n' | cat -bs"), '     1\ttwo\n\n     2\tthree\n');
assert.equal(run('cat --number hello.txt'), '     1\thello world\n     2\tsecond\n');
assert.equal(run("printf 'b\\nA\\nc\\n' | sort --ignore-case"), 'A\nb\nc\n');
assert.match(run('ls -alh --color=auto'), /rw-r--r--.*hello.txt/);
assert.equal(run('ls -alh --color=auto').includes('\x1b[34m'), true);
assert.equal(run('ls -alh --color=auto | cat').includes('\x1b['), false);
assert.equal(run('ls --color=never').includes('\x1b['), false);
assert.match(run('ls --invalid-option'), /arguments/);
assert.equal(run('touch -- -name; cat -- -name'), '');
assert.equal(run('touch -- --number; cat -- --number'), '');
assert.equal(run('printf "a,b,c\\n" | cut -d , -f 1,3'), 'a,c\n');
assert.equal(run('echo "a|b;>c"'), 'a|b;>c\n');
assert.equal(run("echo ''"), '\n');
assert.equal(run('cp hello.txt copy.txt; mv copy.txt moved.txt; cat moved.txt'), 'hello world\nsecond\n');
assert.equal(run('ls *.txt'), 'hello.txt\nmoved.txt\n');
assert.equal(run('cd ../..; cp -r work other; cat other/deep/hello.txt'), 'hello world\nsecond\n');
assert.equal(run('find other -name "*.txt" -type f'), '/home/user/other/deep/hello.txt\n/home/user/other/deep/moved.txt\n');
assert.equal(run('rm -r other; cat other/deep/hello.txt'), 'sh: missing: /home/user/other/deep/hello.txt\n');
assert.equal(run('echo bad > untouched |'), 'sh: syntax\n');
assert.equal(vfs.exists('/home/user/untouched'), false);
assert.equal(run('echo "unterminated'), 'sh: syntax\n');
assert.match(run('rm -rf /'), /protected/);
assert.match(run('mv work work/deep'), /protected/);
assert.match(run('rmdir work'), /empty/);
assert.match(run('cat Desktop'), /file/);
assert.equal(shell.complete('cat wo')[0], 'work/');
assert.equal(shell.run('clear').clear, true);
console.log('Prompt shell checks passed.');
